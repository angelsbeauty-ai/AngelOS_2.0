# Generates src/components/orbShader.ts from the Designer's orbhd.py coefficients (numpy rng seed 7), 1:1 maths.
import json,sys
C=json.load(open(sys.argv[1]))
f=lambda x:f"{x:.6f}"
def sumterms(T,expr):
    return "+".join(expr(*t) for t in T)
lo=sumterms(C['LO'],lambda m,k,p,w,a:f"{f(a)}*sin({f(m)}*th+{f(p)}+{f(w)}*ph*0.6)")
warp=sumterms(C['WARP'],lambda m,k,p,w,a:f"{f(a)}*sin({f(m)}*th+{f(k)}*r+{f(p)}+{f(w)}*ph)")
lays=[]
for li,L in enumerate(C['LAY']):
    s=sumterms(L,lambda m,k,p,w,a,li=li:f"{f(a)}*sin({f(m)}*th+{f(k)}*vw+{f(p)}+{f(w)}*ph*{f(1+li*.5)})")
    lays.append(f"  F=({s})/{f(len(L))}*1.6; dens+=pow(clamp(1.0-abs(F),0.0,1.0),{f(2.2+3.0*li)})*{f((.6,.5,.42,.22)[li])};")
body=f"""
float sq(float x){{ return x*x; }}
float hash(vec2 p){{ return fract(sin(dot(p,vec2(12.9898,78.233)))*43758.5453); }}
float wrapA(float a){{ return atan(sin(a),cos(a)); }}
vec4 orb(vec2 px){{
  vec2 q=(px-0.5*uRes)/uR; float rr=length(q); float th=atan(q.y,q.x);
  float t=uT; float ph=uPhase; float L=uL;
  float r=rr/uScale;
  float d=({lo})*(0.012+0.035*L)/2.2;
  float warp=({warp})/3.0;
  float v=r-1.0-d;
  float pl=exp(-sq(wrapA(th-2.75-0.15*sin(t*0.7))/0.22))+exp(-sq(wrapA(th+0.95-0.15*sin(t*0.7+1.0))/0.22));
  v=v+(-0.45*v/(1.0+exp(-v/0.03)))*pl*(0.6+0.6*L);
  float side=0.5+0.5*cos(th-(2.35+0.25*sin(t*0.4)));
  float sig=0.035+0.07*pow(side,1.5)+0.05*L;
  float envl=exp(-sq((v+0.01*side)/sig));
  float vw=v+0.06*warp; float dens=0.0; float F;
{chr(10).join(lays)}
  float soft=exp(-sq(v/(sig*1.9)))*(0.18+0.1*L);
  float smoke=clamp(envl*dens*(0.85+0.35*L)*(0.55+0.6*side)+soft*(0.5+0.5*side),0.0,1.4);
  float pxs=1.0/(uR*uDpr); float rimr=1.075;
  float ang=0.5+0.5*cos(th+0.75);
  float rim=clamp(1.0-abs(r-rimr)/(1.6*pxs),0.0,1.0)*(0.18+0.55*ang*ang*ang);
  float inner=clamp(1.0-abs(r-(rimr-0.018))/(1.2*pxs),0.0,1.0)*0.10*(0.5+0.5*cos(th-2.3));
  float sheen=exp(-sq((r-0.86)/0.05))*pow(max(cos(th+2.2),0.0),6.0)*0.10;
  float rimA=rim+inner;
  float dth=(hash(px)-hash(px+17.3))/255.0;
  float a=clamp(smoke,0.0,1.0);
  vec4 o;
  if(uNight>0.5){{ vec3 col=vec3(0.97,0.97,0.955)*a+vec3(rimA+sheen); o=vec4(col+dth,clamp(0.92*a+rimA+sheen,0.0,1.0)); }}
  else {{ float a2=0.72*pow(a,1.15); vec3 ink=vec3(0.23,0.22,0.21); float al=clamp(a2+0.55*rimA,0.0,1.0); vec3 col=ink*a2+vec3(0.08)*rimA+vec3(sheen*1.6); o=vec4(col+dth,clamp(al+sheen*0.0,0.0,1.0)); }}
  return o;
}}
"""
U="uniform float uT; uniform float uPhase; uniform float uL; uniform float uScale; uniform float uR; uniform vec2 uRes; uniform float uNight; uniform float uDpr;\n"
sksl=U+body+"half4 main(vec2 p){ return half4(orb(p)); }\n"
glsl="precision highp float;\n"+U+body+"void main(){ vec2 p=vec2(gl_FragCoord.x, uRes.y-gl_FragCoord.y); gl_FragColor=orb(p); }\n"
out="/** GENERATED by scripts/gen-orb-shader.py from the Designer's orbhd.py (ORB_HD_SPEC). Do not edit by hand. Output is premultiplied RGBA. */\n"
out+=f"export const ORB_SKSL = {json.dumps(sksl)};\nexport const ORB_GLSL = {json.dumps(glsl)};\n"
open(sys.argv[2],'w').write(out)
