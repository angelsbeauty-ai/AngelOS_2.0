import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dir = path.dirname(fileURLToPath(import.meta.url));
const iconDir = path.join(__dir, '..', 'apps', 'mobile', 'assets', 'tabs');

